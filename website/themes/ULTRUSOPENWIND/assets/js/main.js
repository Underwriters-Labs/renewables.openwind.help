document.addEventListener('DOMContentLoaded', function () {
  // Sidebar open/close (mobile)
  var toggle = document.querySelector('.sidebar-toggle');
  var sidebar = document.getElementById('site-sidebar');

  if (toggle && sidebar) {
    toggle.addEventListener('click', function () {
      var opened = sidebar.classList.toggle('open');
      toggle.setAttribute('aria-expanded', opened ? 'true' : 'false');
    });

    // close when clicking outside
    document.addEventListener('click', function (e) {
      if (!sidebar.classList.contains('open')) return;
      if (sidebar.contains(e.target) || toggle.contains(e.target)) return;
      sidebar.classList.remove('open');
      toggle.setAttribute('aria-expanded', 'false');
    });
  }

  // close with Escape
  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' && sidebar && sidebar.classList.contains('open')) {
      sidebar.classList.remove('open');
      if (toggle) toggle.setAttribute('aria-expanded', 'false');
    }
  });

  // Collapse/expand control (desktop)
  var collapseBtn = document.querySelector('.sidebar-collapse-toggle');
  var sidebarCollapsedKey = 'sidebar-collapsed';

  function setCollapsed(collapsed, persist) {
    if (!sidebar) return;
    if (collapsed) {
      sidebar.classList.add('collapsed');
      if (collapseBtn) collapseBtn.setAttribute('aria-expanded', 'false');
    } else {
      sidebar.classList.remove('collapsed');
      if (collapseBtn) collapseBtn.setAttribute('aria-expanded', 'true');
    }
    if (persist) {
      try { localStorage.setItem(sidebarCollapsedKey, collapsed ? '1' : '0'); } catch (e) { /* ignore */ }
    }
  }

  if (collapseBtn && sidebar) {
    var persisted = null;
    try { persisted = localStorage.getItem(sidebarCollapsedKey); } catch (e) { persisted = null; }
    if (persisted !== null && window.innerWidth > 920) {
      setCollapsed(persisted === '1', false);
    }

    collapseBtn.addEventListener('click', function () {
      var isCollapsed = sidebar.classList.toggle('collapsed');
      collapseBtn.setAttribute('aria-expanded', isCollapsed ? 'false' : 'true');
      try { localStorage.setItem(sidebarCollapsedKey, isCollapsed ? '1' : '0'); } catch (e) {}
    });
  }

  // ---------------------------
  // Client-side fuzzy search
  // ---------------------------
  var searchInput = document.getElementById('site-search-input');
  var searchResultsEl = document.getElementById('site-search-results');
  var searchIndex = null;
  var activeIndex = -1;

  function loadSearchIndex() {
    if (searchIndex) return Promise.resolve(searchIndex);
    return fetch('/js/search-index.json').then(function (r) { return r.json(); }).then(function (data) {
      searchIndex = data || [];
      return searchIndex;
    }).catch(function () { searchIndex = []; return searchIndex; });
  }

  function normalize(s){ return (s||'').toString().toLowerCase(); }

  // simple fuzzy scoring - lower is better
  function fuzzyScore(text, query){
    text = normalize(text);
    query = normalize(query);
    if (!query) return null;
    // exact substring matches score low
    var idx = text.indexOf(query);
    if (idx !== -1) return idx;

    // sequential match: find characters in order
    var pos = 0, score = 0;
    for (var i=0;i<query.length;i++){
      var c = query[i];
      var found = text.indexOf(c, pos);
      if (found === -1) return null;
      score += found - pos; // penalty for distance
      pos = found+1;
    }
    return score;
  }

  function search(query){
    query = (query||'').trim();
    if (!query) return Promise.resolve([]);
    return loadSearchIndex().then(function (idx){
      var results = [];
      idx.forEach(function (item){
        var text = (item.title || '') + ' ' + (item.summary || '');
        var s = fuzzyScore(text, query);
        if (s !== null) results.push({score:s, item:item});
      });
      results.sort(function(a,b){ return a.score - b.score; });
      return results.slice(0,12).map(function(r){ return r.item; });
    });
  }

  function renderResults(items){
    if (!searchResultsEl) return;
    searchResultsEl.innerHTML = '';
    activeIndex = -1;
    if (!items || !items.length){
      searchResultsEl.setAttribute('hidden','');
      return;
    }
    searchResultsEl.removeAttribute('hidden');
    items.forEach(function (it, i){
      var a = document.createElement('a');
      a.className = 'result';
      a.href = it.link;
      a.setAttribute('role','option');
      var summaryText = it.summary ? escapeHtml(truncate(it.summary, 50)) : '';
      a.innerHTML = '<span class="title">'+escapeHtml(it.title)+'</span>' + (summaryText ? '<span class="summary">'+summaryText+'</span>' : '');
      a.addEventListener('click', function(){ if (searchResultsEl) searchResultsEl.setAttribute('hidden',''); });
      searchResultsEl.appendChild(a);
    });
  }

  function escapeHtml(s){ return (s||'').toString().replace(/[&<>"']/g, function(c){ return ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'})[c]; }); }

  // truncate a string to `n` characters and append an ellipsis if trimmed
  function truncate(s, n){
    s = (s||'').toString();
    if (s.length <= n) return s;
    return s.slice(0, n).replace(/\s+$/,'') + '…';
  }

  if (searchInput && searchResultsEl){
    var searchTimer = null;
    searchInput.addEventListener('input', function(e){
      clearTimeout(searchTimer);
      var q = searchInput.value;
      searchTimer = setTimeout(function(){
        if (!q || q.length < 2){ renderResults([]); return; }
        search(q).then(renderResults);
      }, 150);
    });

    // keyboard navigation
    searchInput.addEventListener('keydown', function (e){
      var items = searchResultsEl.querySelectorAll('.result');
      if (!items.length) return;
      if (e.key === 'ArrowDown'){
        e.preventDefault(); activeIndex = Math.min(activeIndex+1, items.length-1);
        updateActive(items);
      } else if (e.key === 'ArrowUp'){
        e.preventDefault(); activeIndex = Math.max(activeIndex-1, 0);
        updateActive(items);
      } else if (e.key === 'Enter'){
        if (activeIndex >= 0 && items[activeIndex]){
          window.location = items[activeIndex].href;
        }
      } else if (e.key === 'Escape'){
        searchResultsEl.setAttribute('hidden','');
      }
    });

    function updateActive(items){
      items.forEach(function(it, i){ it.setAttribute('aria-selected', (i===activeIndex) ? 'true' : 'false'); });
      if (activeIndex >= 0 && items[activeIndex]) items[activeIndex].scrollIntoView({block:'nearest'});
    }

    // hide results when clicking away
    document.addEventListener('click', function (e){
      if (!searchResultsEl.contains(e.target) && e.target !== searchInput){
        searchResultsEl.setAttribute('hidden','');
      }
    });

  }

});
